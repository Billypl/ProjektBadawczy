"""Why do all models fail on rivers? Error breakdown river_like vs sea_like (for H3).

    python scripts/river_analysis.py --methods m0_ewasr_val m1_segformer_b2_val m2_yolo26s_val_c010_unobst \
        --labels eWaSR SegFormer-B2 YOLO26s-seg

Sources: the evaluator's frames.csv (TP/FP/FN, WE_acc per frame) and segments.json
(area and class of every TP/FP/FN segment), LaRS image_annotations.json (scene
attributes). The only quantity not taken from the evaluator is the FP-pixel
location diagnostic: pixels predicted as obstacle where GT is water, binned by the
distance to the nearest non-water GT pixel (shore / obstacle). It is a diagnostic,
not a benchmark metric.

Writes results/river_analysis.md (aggregates only) and, with --figures, overlays of
the worst river frames to results/figures/rivers/ (gitignored, contains LaRS images).
"""

import argparse
import json
from pathlib import Path

import cv2
import numpy as np
import pandas as pd
from PIL import Image

from common.interfaces import OBSTACLE, WATER
from usvseg.data.lars import Lars
from usvseg.data.taxonomy import color_to_labels
from usvseg.viz.overlay import overlay, side_by_side

REPO = Path(__file__).resolve().parents[1]
AREA_BINS = [0, 100, 1000, 10000, np.inf]
AREA_LABELS = ["<100 px", "100-1k", "1k-10k", ">10k"]
DIST_BINS = [0, 10, 50, 150, np.inf]
DIST_LABELS = ["<10 px", "10-50", "50-150", ">150"]
SPECIAL = ["glitter", "plants_debris", "wakes", "fog", "dirty_lens", "extra_dark", "extra_bright", "rain"]


def f1_table(df: pd.DataFrame, by: str) -> pd.DataFrame:
    g = df.groupby(by)[["TP", "FP", "FN"]].sum()
    g["Pr"] = 100 * g.TP / (g.TP + g.FP).clip(lower=1)
    g["Re"] = 100 * g.TP / (g.TP + g.FN).clip(lower=1)
    g["F1"] = 200 * g.TP / (2 * g.TP + g.FP + g.FN).clip(lower=1)
    g["FP/frame"] = g.FP / df.groupby(by).size()
    g["mu_frames"] = df.groupby(by)["WE_acc"].mean()  # mean of per-frame WE_acc, not the global mu
    g["n"] = df.groupby(by).size()
    return g.round(1)


def segments(exp: str) -> pd.DataFrame:
    s = json.loads((REPO / "runs" / exp / "eval" / exp / "segments.json").read_text())
    return pd.DataFrame([{**seg, "image": f["image_name"]} for f in s["frames"] for seg in f["segment_data"]])


def pred_labels(exp: str, name: str) -> np.ndarray:
    return color_to_labels(np.asarray(Image.open(REPO / "runs" / exp / "preds" / exp / f"{name}.png").convert("RGB")))


def fp_pixel_distance(exp: str, ds: Lars, names: list[str]) -> pd.Series:
    """Share of 'obstacle on GT water' pixels per distance-to-shore bin."""
    counts = np.zeros(len(DIST_LABELS))
    for n in names:
        gt = ds.by_name(n).semantic()
        water = (gt == WATER).astype(np.uint8)
        dist = cv2.distanceTransform(water, cv2.DIST_L2, 5)
        fp = (pred_labels(exp, n) == OBSTACLE) & (gt == WATER)
        counts += np.histogram(dist[fp], bins=DIST_BINS)[0]
    return pd.Series(100 * counts / max(counts.sum(), 1), index=DIST_LABELS).round(1)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--methods", nargs="+", required=True)
    ap.add_argument("--labels", nargs="+", required=True)
    ap.add_argument("--split", default="val")
    ap.add_argument("--figures", type=int, default=0, help="save overlays of the N worst river frames")
    ap.add_argument("--out", type=Path, default=REPO / "results" / "river_analysis.md")
    args = ap.parse_args()

    ds = Lars(args.split)
    ann = {a["file_name"].rsplit(".", 1)[0]: a["labels"] for a in ds.image_annotations["annotations"]}
    cats = {c["id"]: c["name"] for c in ds.panoptic_annotations["categories"]}
    train_scenes = pd.Series([ann_t["labels"]["scene_type"] for ann_t in Lars("train").image_annotations["annotations"]
                              if ann_t["file_name"].rsplit(".", 1)[0] in set(s.name for s in Lars("train").samples)])

    out = ["# River vs sea error analysis (LaRS val)", "",
           f"Generated by `scripts/river_analysis.py`. Methods: {', '.join(f'{l} = `{m}`' for m, l in zip(args.methods, args.labels))}.",
           "", f"Training data scene mix (LaRS train minus dev): {train_scenes.value_counts().to_dict()}. "
           f"Val: {pd.Series([a['scene_type'] for a in ann.values()]).value_counts().to_dict()}.", ""]

    frames = {}
    for exp, lbl in zip(args.methods, args.labels):
        f = pd.read_csv(REPO / "runs" / exp / "eval" / exp / "frames.csv", index_col="image")
        for k in ("scene_type", "reflections", "waves", "lighting"):
            f[k] = [ann[n].get(k) for n in f.index]
        for k in SPECIAL:
            f[k] = [ann[n]["special"].get(k, False) for n in f.index]
        frames[lbl] = f

    out += ["## 1. Detection by scene type", ""]
    for lbl, f in frames.items():
        out += [f"**{lbl}**", "", f1_table(f, "scene_type").to_markdown(), ""]

    out += ["## 2. River frames by attribute (FP/frame and F1)", "",
            "Rows with n < 5 are noise.", ""]
    for key in ("reflections", "waves", "lighting"):
        rows = {lbl: f1_table(f[f.scene_type == "river_like"], key)[["TP", "FN", "F1", "FP/frame", "n"]]
                for lbl, f in frames.items()}
        t = pd.concat(rows, axis=1)
        t.columns = [f"{m} {c}" for m, c in t.columns]
        out += [f"by {key}:", "", t.to_markdown(), ""]
    rows = []
    for k in SPECIAL:
        for scene in ("river_like", "sea_like"):
            n = int(next(iter(frames.values())).query("scene_type == @scene")[k].sum())
            if n == 0:
                continue
            row = {"flag": k, "scene": scene, "n": n}
            for lbl, f in frames.items():
                sub = f[(f.scene_type == scene) & f[k]]
                row[f"{lbl} FP/frame"] = round(sub.FP.sum() / n, 1)
            rows.append(row)
    out += ["special flags (frames with the flag set):", "", pd.DataFrame(rows).to_markdown(index=False), ""]

    out += ["## 3. FP concentration", "",
            "Share of all river FP produced by the worst 10% of river frames.", ""]
    rows = []
    for lbl, f in frames.items():
        for scene in ("river_like", "sea_like"):
            fp = f[f.scene_type == scene].FP.sort_values(ascending=False)
            k = max(1, round(0.1 * len(fp)))
            rows.append({"method": lbl, "scene": scene, "FP": int(fp.sum()),
                         "top 10% frames share": round(100 * fp.iloc[:k].sum() / max(fp.sum(), 1), 1),
                         "frames with 0 FP": int((fp == 0).sum()), "n": len(fp)})
    out += [pd.DataFrame(rows).to_markdown(index=False), ""]

    out += ["## 4. FP segment size (evaluator segments.json)", "", "Share of FP segments per area bin.", ""]
    rows, fn_rows = [], []
    for exp, lbl in zip(args.methods, args.labels):
        s = segments(exp)
        s["scene"] = [ann[n]["scene_type"] for n in s.image]
        s["area_bin"] = pd.cut(s.area, AREA_BINS, labels=AREA_LABELS, right=False)
        for scene in ("river_like", "sea_like"):
            fp = s[(s.type == "FP") & (s.scene == scene)]
            rows.append({"method": lbl, "scene": scene, "FP": len(fp),
                         **(100 * fp.area_bin.value_counts(normalize=True)).round(1).reindex(AREA_LABELS).to_dict()})
            gt = s[s.type.isin(["TP", "FN"]) & (s.scene == scene)]
            per_cls = gt.groupby("category_id").type.agg(n="size", fn=lambda t: (t == "FN").sum())
            for c, r in per_cls.iterrows():
                fn_rows.append({"class": cats[int(c)], "scene": scene, "n": r.n, "method": lbl,
                                "FN %": round(100 * r.fn / r.n, 1)})
    out += [pd.DataFrame(rows).to_markdown(index=False), ""]
    out += ["## 5. Missed obstacles (FN rate % per GT class)", "",
            "n = GT obstacles of that class.", "",
            pd.DataFrame(fn_rows).pivot_table(index=["scene", "class", "n"], columns="method", values="FN %")
            [args.labels].reset_index().to_markdown(index=False), ""]

    out += ["## 6. Where are the false obstacle pixels? (own diagnostic, not an evaluator metric)", "",
            "Pixels predicted as obstacle where GT is water, by distance to the nearest non-water GT pixel "
            "(shore, static or dynamic obstacle). Share in %.", ""]
    rows = []
    for exp, lbl in zip(args.methods, args.labels):
        for scene in ("river_like", "sea_like"):
            names = [n for n, a in ann.items() if a["scene_type"] == scene]
            rows.append({"method": lbl, "scene": scene, **fp_pixel_distance(exp, ds, names).to_dict()})
    out += [pd.DataFrame(rows).to_markdown(index=False), ""]

    total = sum(f.FP for f in frames.values())
    river = total[next(iter(frames.values())).scene_type == "river_like"].sort_values(ascending=False)
    ref = next(iter(frames.values()))
    worst = river.index[:10]
    tbl = pd.DataFrame({lbl: f.loc[worst, "FP"] for lbl, f in frames.items()})
    tbl["reflections"] = ref.loc[worst, "reflections"]
    tbl["waves"] = ref.loc[worst, "waves"]
    tbl["flags"] = [", ".join(k for k in SPECIAL if ref.loc[n, k]) for n in worst]
    out += ["## 7. Worst river frames (sum of FP over all methods)", "", tbl.to_markdown(), ""]

    args.out.write_text("\n".join(out))
    print(f"-> {args.out}")

    if args.figures:
        fig_dir = REPO / "results" / "figures" / "rivers"
        fig_dir.mkdir(parents=True, exist_ok=True)
        for n in river.index[: args.figures]:
            img = ds.by_name(n).image()
            panels = [img, overlay(img, ds.by_name(n).semantic())] + [overlay(img, pred_labels(m, n)) for m in args.methods]
            titles = ["image", "GT"] + [f"{lbl} (FP {frames[lbl].FP[n]})" for lbl in args.labels]
            Image.fromarray(side_by_side(panels, titles, height=300)).save(fig_dir / f"{n}.jpg", quality=90)
        print(f"{args.figures} figures -> {fig_dir}")


if __name__ == "__main__":
    main()
